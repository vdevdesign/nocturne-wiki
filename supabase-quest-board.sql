-- Run this in the Supabase SQL editor to enable the quest and rumor board.
CREATE TABLE IF NOT EXISTS public.quest_board (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_type text NOT NULL CHECK (entry_type IN ('quest', 'rumor')),
  status text NOT NULL CHECK (
    (entry_type = 'quest' AND status IN ('open', 'in_progress', 'completed'))
    OR (entry_type = 'rumor' AND status IN ('unverified', 'confirmed', 'false'))
  ),
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  reward text NOT NULL DEFAULT '',
  visible_to_players boolean NOT NULL DEFAULT true,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.campaign_dashboard (
  id smallint PRIMARY KEY CHECK (id = 1),
  next_session_date date,
  next_session_notes text NOT NULL DEFAULT '',
  updated_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

