ALTER TABLE public.quest_board ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.quest_board TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.quest_board_id_seq TO authenticated;
ALTER TABLE public.campaign_dashboard ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE ON TABLE public.campaign_dashboard TO authenticated;

DROP POLICY IF EXISTS campaign_dashboard_select ON public.campaign_dashboard;
CREATE POLICY campaign_dashboard_select
  ON public.campaign_dashboard FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS campaign_dashboard_insert ON public.campaign_dashboard;
CREATE POLICY campaign_dashboard_insert
  ON public.campaign_dashboard FOR INSERT TO authenticated
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.profiles
      WHERE profiles.id = (SELECT auth.uid())
        AND profiles.role = 'dm'
    )
  );

DROP POLICY IF EXISTS campaign_dashboard_update ON public.campaign_dashboard;
CREATE POLICY campaign_dashboard_update
  ON public.campaign_dashboard FOR UPDATE TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.profiles
      WHERE profiles.id = (SELECT auth.uid())
