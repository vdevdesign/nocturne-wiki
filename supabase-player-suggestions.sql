create table if not exists public.player_suggestions (
  id bigint generated by default as identity primary key,
  requested_by uuid not null references auth.users(id) on delete cascade,
  requester_name text not null,
  message text not null check (length(trim(message)) between 1 and 1000),
  status text not null default 'pending' check (status in ('pending', 'handled')),
  created_at timestamptz not null default now(),
  handled_by uuid references auth.users(id),
  handled_at timestamptz
);

alter table public.player_suggestions enable row level security;

revoke all on table public.player_suggestions from public, anon, authenticated;
grant insert on table public.player_suggestions to authenticated;
grant select, update on table public.player_suggestions to authenticated;
grant usage, select on sequence public.player_suggestions_id_seq to authenticated;

drop policy if exists "Players can submit suggestions" on public.player_suggestions;
create policy "Players can submit suggestions" on public.player_suggestions
for insert to authenticated
with check (
  requested_by = (select auth.uid())
  and status = 'pending'
  and handled_by is null
  and handled_at is null
  and length(trim(message)) between 1 and 1000
);

drop policy if exists "DMs can read suggestions" on public.player_suggestions;
create policy "DMs can read suggestions" on public.player_suggestions
for select to authenticated
using (exists (
  select 1 from public.profiles
  where profiles.id = (select auth.uid()) and profiles.role = 'dm'
));

drop policy if exists "DMs can handle suggestions" on public.player_suggestions;
create policy "DMs can handle suggestions" on public.player_suggestions
for update to authenticated
using (exists (
  select 1 from public.profiles
  where profiles.id = (select auth.uid()) and profiles.role = 'dm'
))
with check (exists (
  select 1 from public.profiles
  where profiles.id = (select auth.uid()) and profiles.role = 'dm'
));
